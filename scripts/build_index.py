#!/usr/bin/env python
"""Rebuild reference/INDEX.md: one line per knowledge file (reference/**/*.md plus the living memory/ files).

Generated, never hand-edited, so it cannot drift (Spencer, 2026-10-31, after comparing systems with G).
Runs from the PostToolUse hook on every Write/Edit and rewrites the file only when its content changed.

Line format:  - `path` (NN KB) — Title — first sentence of the file
Usage: python scripts/build_index.py [--quiet]
"""
import io
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "reference", "INDEX.md")
LIVING_MEMORY = ["memory/followups-queue.md", "memory/outreach-log.md"]
SKIP_DIRS = {"__pycache__"}
MAX_SUMMARY = 90


def clean(s):
    s = re.sub(r"<!--.*?-->", "", s)
    s = re.sub(r"[*_`>#]+", "", s)
    s = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", s)
    s = re.sub(r"\s+", " ", s).strip()
    return s


def describe(path):
    try:
        with io.open(path, encoding="utf-8") as f:
            lines = f.read().split("\n")
    except (OSError, UnicodeDecodeError):
        return "", ""
    title, summary = "", ""
    in_status = False
    for l in lines:
        s = l.strip()
        if not s:
            continue
        if s == "<!-- status-block:start -->":
            in_status = True
            continue
        if s == "<!-- status-block:end -->":
            in_status = False
            continue
        if not title and s.startswith("# "):
            title = clean(s)
            continue
        if title and not summary:
            if in_status and not s.startswith("> **In short:**"):
                continue
            if s.startswith("|") or s.startswith("---") or s.startswith("#"):
                continue
            summary = clean(s)
            if len(summary) > MAX_SUMMARY:
                cut = summary[:MAX_SUMMARY]
                summary = cut[: cut.rfind(" ")] + " ..."
            break
    if not title:
        title = os.path.splitext(os.path.basename(path))[0]
    return title, summary


def files():
    out = []
    for dp, dns, fns in os.walk(os.path.join(ROOT, "reference")):
        dns[:] = sorted(d for d in dns if d not in SKIP_DIRS)
        for fn in sorted(fns):
            if fn.lower().endswith(".md") and os.path.join(dp, fn) != OUT:
                out.append(os.path.relpath(os.path.join(dp, fn), ROOT).replace(os.sep, "/"))
    for p in LIVING_MEMORY:
        if os.path.exists(os.path.join(ROOT, p)):
            out.append(p)
    return out


def main():
    quiet = "--quiet" in sys.argv
    rows = ["# INDEX — every knowledge file, one line each", "",
            "_Generated by `scripts/build_index.py` on every write (PostToolUse hook). Do not edit by hand; fix the file's title or first line instead._",
            "_Read this to find the right file; read the file itself before relying on anything in it._", ""]
    cur = None
    for p in files():
        d = os.path.dirname(p)
        if d != cur:
            cur = d
            rows += ["", "## " + d + "/", ""]
        kb = max(1, os.path.getsize(os.path.join(ROOT, p)) // 1024)
        title, summary = describe(os.path.join(ROOT, p))
        line = "- `%s` (%d KB) — %s" % (p, kb, title)
        if summary and summary != title:
            line += " — " + summary
        rows.append(line)
    text = "\n".join(rows) + "\n"
    old = None
    if os.path.exists(OUT):
        with io.open(OUT, encoding="utf-8") as f:
            old = f.read()
    if old != text:
        with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        if not quiet:
            print("INDEX.md rebuilt: %d files" % sum(1 for r in rows if r.startswith("- `")))
    elif not quiet:
        print("INDEX.md unchanged")


if __name__ == "__main__":
    main()
